import { useEffect, useRef, useState } from 'react';
import { BookOpen, CircleCheck, Cpu, ExternalLink, LoaderCircle, Send, Square, X } from 'lucide-react';
import Badge, { STATUS_META } from '../Badge.jsx';

const VERDICT = {
  eligible: 'all conditions are satisfied, so the citizen is Eligible.',
  potential: 'no condition failed, but some information is missing, so the citizen is Potentially Eligible — not rejected.',
  not_eligible: 'at least one mandatory condition failed, so the citizen is Not Eligible.',
};

export default function RagDrawer({ result, docs, onClose }) {
  const last = useRef(result);
  if (result) last.current = result;
  const shown = last.current;
  const open = Boolean(result);

  const [question, setQuestion] = useState('');
  const [thread, setThread] = useState([]);
  const timers = useRef([]);

  useEffect(() => {
    setThread([]);
    setQuestion('');
  }, [result?.id]);

  useEffect(() => () => timers.current.forEach(clearTimeout), []);

  useEffect(() => {
    if (!open) return undefined;
    const onKey = (e) => e.key === 'Escape' && onClose();
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [open, onClose]);

  const ask = (e) => {
    e.preventDefault();
    const q = question.trim();
    if (!q || !shown) return;
    setQuestion('');
    const id = `${Date.now()}-${Math.random()}`;
    const answer = shown.scheme.rag.qa;
    setThread((t) => [...t, { id, q, a: null }]);
    timers.current.push(setTimeout(() => setThread((t) => t.map((m) => (m.id === id ? { ...m, a: answer } : m))), 800));
  };

  return (
    <div className={`fixed inset-0 z-[1200] ${open ? '' : 'pointer-events-none'}`} inert={!open}>
      <div className={`absolute inset-0 bg-slate-950/40 transition-opacity ${open ? 'opacity-100' : 'opacity-0'}`} onClick={onClose} />
      <aside
        role="dialog"
        aria-modal="true"
        aria-label="RAG explanation"
        className={`absolute inset-y-0 right-0 flex w-full max-w-xl flex-col bg-white shadow-2xl transition-transform duration-300 ${
          open ? 'translate-x-0' : 'translate-x-full'
        }`}
      >
        {shown && (
          <>
            <header className="flex items-start gap-3 border-b border-slate-200 px-5 py-4">
              <div className="grid h-8 w-8 shrink-0 place-items-center rounded-md bg-slate-900 text-xs font-bold text-white">5</div>
              <div className="min-w-0 flex-1">
                <p className="text-[11px] font-semibold uppercase tracking-wide text-slate-500">Explainable RAG</p>
                <h2 className="text-base font-bold text-slate-950">{shown.scheme.name}</h2>
                <div className="mt-1">
                  <Badge tone={STATUS_META[shown.status].tone}>Rule engine verdict: {STATUS_META[shown.status].label}</Badge>
                </div>
              </div>
              <button type="button" onClick={onClose} className="rounded-md p-1.5 text-slate-500 hover:bg-slate-100" aria-label="Close">
                <X className="h-5 w-5" />
              </button>
            </header>

            <div className="flex-1 space-y-5 overflow-y-auto px-5 py-4 text-sm">
              <section className="space-y-2">
                <h3 className="text-xs font-bold uppercase tracking-wide text-slate-500">Grounded explanation</h3>
                <p className="text-slate-800">
                  The rule engine evaluated {shown.total} conditions: {shown.satisfied.length} satisfied, {shown.failed.length} not
                  satisfied, {shown.missing.length} missing — {VERDICT[shown.status]} <sup className="text-blue-700">[1]</sup>
                </p>
                {(shown.failed.length > 0 || shown.missing.length > 0) && (
                  <ul className="list-disc space-y-1 pl-5 text-slate-700">
                    {shown.failed.map((c) => (
                      <li key={c.label}>{c.detail}.</li>
                    ))}
                    {shown.missing.map((c) => (
                      <li key={c.label}>
                        {c.label}: {c.detail.toLowerCase()} — {c.resolveDocId ? 'upload' : 'provide'} {c.resolve}.
                      </li>
                    ))}
                  </ul>
                )}
                <p className="text-slate-700">
                  {shown.scheme.rag.summary} <sup className="text-blue-700">[1]{shown.scheme.rag.sources.length > 1 && '[2]'}</sup>
                </p>
                <p className="flex items-start gap-1.5 rounded-md bg-slate-50 p-2 text-[11px] text-slate-600 ring-1 ring-slate-200">
                  <Cpu className="mt-0.5 h-3.5 w-3.5 shrink-0" />
                  Generated by local LLM (Ollama) with Gemini fallback from {shown.scheme.rag.sources.length * 2} FAISS-retrieved chunks.
                  The LLM explains the rule engine's result; it cannot change it.
                </p>
              </section>

              <section className="space-y-2">
                <h3 className="text-xs font-bold uppercase tracking-wide text-slate-500">Required documents</h3>
                <ul className="space-y-1.5">
                  {shown.scheme.rag.documents.map((d) => {
                    const have = d.docId && docs[d.docId]?.status === 'done';
                    return (
                      <li key={d.label} className="flex items-center gap-2">
                        {have ? <CircleCheck className="h-4 w-4 text-emerald-600" /> : <Square className="h-4 w-4 text-slate-400" />}
                        <span className={have ? 'text-slate-900' : 'text-slate-600'}>{d.label}</span>
                        {have && <Badge tone="green">Uploaded</Badge>}
                      </li>
                    );
                  })}
                </ul>
              </section>

              <section className="space-y-2">
                <h3 className="text-xs font-bold uppercase tracking-wide text-slate-500">How to apply</h3>
                <ol className="space-y-2">
                  {shown.scheme.rag.steps.map((s, i) => (
                    <li key={s} className="flex gap-2.5">
                      <span className="grid h-5 w-5 shrink-0 place-items-center rounded-full bg-slate-200 text-[11px] font-bold text-slate-700">{i + 1}</span>
                      <span className="text-slate-700">{s}</span>
                    </li>
                  ))}
                </ol>
              </section>

              <section className="space-y-2">
                <h3 className="text-xs font-bold uppercase tracking-wide text-slate-500">Cited official sources</h3>
                <ul className="space-y-2">
                  {shown.scheme.rag.sources.map((s, i) => (
                    <li key={s.title} className="rounded-md border border-slate-200 p-2.5">
                      <div className="flex items-start justify-between gap-2">
                        <p className="text-xs font-semibold text-slate-900">
                          [{i + 1}] {s.title}
                        </p>
                        <Badge tone="blue">sim {s.score.toFixed(2)}</Badge>
                      </div>
                      <p className="text-[11px] text-slate-500">{s.ref}</p>
                      <a href={s.url} target="_blank" rel="noreferrer" className="mt-1 inline-flex items-center gap-1 text-[11px] font-medium text-blue-700 hover:underline">
                        {s.url.replace('https://', '')}
                        <ExternalLink className="h-3 w-3" />
                      </a>
                    </li>
                  ))}
                </ul>
              </section>

              <section className="space-y-2">
                <h3 className="flex items-center gap-1.5 text-xs font-bold uppercase tracking-wide text-slate-500">
                  <BookOpen className="h-3.5 w-3.5" />
                  Ask about this scheme
                </h3>
                {thread.map((m) => (
                  <div key={m.id} className="space-y-1.5">
                    <p className="ml-auto w-fit max-w-[85%] rounded-lg bg-slate-900 px-3 py-1.5 text-xs text-white">{m.q}</p>
                    <p className="w-fit max-w-[90%] rounded-lg bg-slate-100 px-3 py-1.5 text-xs text-slate-800">
                      {m.a ?? (
                        <span className="flex items-center gap-1.5 text-slate-500">
                          <LoaderCircle className="h-3.5 w-3.5 animate-spin" /> Retrieving from circulars…
                        </span>
                      )}
                      {m.a && <sup className="text-blue-700"> [1]</sup>}
                    </p>
                  </div>
                ))}
              </section>
            </div>

            <form onSubmit={ask} className="flex gap-2 border-t border-slate-200 px-5 py-3">
              <input
                value={question}
                onChange={(e) => setQuestion(e.target.value)}
                placeholder="e.g. Does this cover hostel fees?"
                className="flex-1 rounded-md border border-slate-300 px-3 py-2 text-sm focus:border-slate-900 focus:outline-none"
              />
              <button type="submit" className="flex items-center gap-1.5 rounded-md bg-slate-900 px-3 py-2 text-sm font-semibold text-white hover:bg-slate-700">
                <Send className="h-4 w-4" />
                Ask
              </button>
            </form>
          </>
        )}
      </aside>
    </div>
  );
}
