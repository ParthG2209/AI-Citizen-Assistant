"""Deterministic SYNTHETIC demonstration dataset for district analytics.

NOT GOVERNMENT DATA. Only the district names and centroids are real (from data/geo/mp_districts.geojson);
blocks, villages, households, citizens, eligibility statuses, enrolments and missing documents are
pseudo-random draws from a seeded ``random.Random``. Block and village names are generic
("Block 03 (synthetic)") because no official block list is bundled with this repository.

The eligibility statuses below are NOT produced by the rule engine and say nothing about real scheme
rules: target groups and probabilities only exist to make the demo data look plausible
(e.g. student schemes are drawn for 16-25 year olds). They are documented in ``SCHEME_DRAWS``.

Files written to the output directory (schema in data/raw/census/README.md):
``manifest.json``, ``blocks.csv``, ``villages.csv``, ``scheme_status.csv``.
Same seed + same parameters + same scheme catalog -> byte-identical files.
"""

from __future__ import annotations

import csv
import json
import random
from collections.abc import Mapping, Sequence
from dataclasses import asdict, dataclass, field
from pathlib import Path

from ai_modules.analytics.reference import REPO_ROOT, District, SchemeInfo

DATASET_LABEL = "SYNTHETIC-MP-DEMO-v1"
GENERATOR_VERSION = "1"
DEFAULT_SEED = 20261118
DEFAULT_INPUT_DIR = REPO_ROOT / "data" / "raw" / "census" / "synthetic_mp_v1"
NOT_GOVERNMENT_DATA = (
    "SYNTHETIC demonstration data generated by ai_modules/analytics/synthetic.py. Not government data; "
    "only district names and centroids are real."
)

# The frontend district list (frontend/src/data/mockData.js MP_DISTRICTS) -> real district ids.
DEFAULT_DISTRICTS: tuple[str, ...] = (
    "bhopal",
    "sehore",
    "raisen",
    "vidisha",
    "narmadapuram",
    "indore",
    "jabalpur",
    "gwalior",
    "ujjain",
    "sagar",
    "rewa",
    "chhindwara",
)

BLOCK_COLUMNS = ("block_id", "block_name", "district_id", "is_synthetic", "dataset_label")
VILLAGE_COLUMNS = (
    "village_id",
    "village_name",
    "block_id",
    "district_id",
    "households",
    "population",
    "is_synthetic",
    "dataset_label",
)
STATUS_COLUMNS = (
    "record_id",
    "citizen_id",
    "household_id",
    "village_id",
    "scheme_id",
    "eligibility_status",
    "enrolled",
    "missing_documents",
    "is_synthetic",
    "dataset_label",
)
DOCUMENT_SEPARATOR = "|"


@dataclass(frozen=True, slots=True)
class SchemeDraw:
    """Synthetic sampling parameters for one scheme id (demo plausibility only, not eligibility rules).

    ``target``: ``household`` (drawn once per household head), ``student`` (members aged 16-25),
    ``rural_female_student`` (female members aged 16-25 in a village) or ``adult`` (members aged 18+).
    """

    target: str
    eligible_rate: float
    potential_rate: float
    enrol_rate: float


SCHEME_DRAWS: dict[str, SchemeDraw] = {
    "pm_kisan": SchemeDraw("household", 0.55, 0.10, 0.80),
    "pm_jay": SchemeDraw("household", 0.60, 0.10, 0.62),
    "pmay_gramin": SchemeDraw("household", 0.25, 0.08, 0.70),
    "post_matric_scholarship_obc": SchemeDraw("student", 0.30, 0.10, 0.50),
    "hostel_assistance": SchemeDraw("student", 0.15, 0.08, 0.45),
    "mp_kisan_kalyan": SchemeDraw("household", 0.50, 0.10, 0.75),
    "laptop_protsahan": SchemeDraw("student", 0.10, 0.05, 0.65),
    "mmvy": SchemeDraw("student", 0.12, 0.06, 0.60),
    "gaon_ki_beti": SchemeDraw("rural_female_student", 0.45, 0.10, 0.40),
}
# Used for any scheme id that appears in the rule catalog later but has no entry above.
DEFAULT_DRAW = SchemeDraw("adult", 0.10, 0.05, 0.55)


@dataclass(frozen=True, slots=True)
class SyntheticConfig:
    seed: int = DEFAULT_SEED
    district_ids: tuple[str, ...] = DEFAULT_DISTRICTS
    blocks_per_district: tuple[int, int] = (4, 7)
    villages_per_block: tuple[int, int] = (5, 10)
    households_per_village: tuple[int, int] = (15, 40)
    members_per_household: tuple[int, int] = (1, 6)
    # Probability that each required document is missing for an eligible-but-not-enrolled record.
    missing_document_rate: float = 0.35
    dataset_label: str = DATASET_LABEL


@dataclass(slots=True)
class SyntheticDataset:
    blocks: list[dict[str, str]] = field(default_factory=list)
    villages: list[dict[str, str]] = field(default_factory=list)
    scheme_status: list[dict[str, str]] = field(default_factory=list)
    manifest: dict = field(default_factory=dict)


def _clip(value: float, low: float = 0.03, high: float = 0.97) -> float:
    return max(low, min(high, value))


def _bool(value: bool) -> str:
    return "true" if value else "false"


def generate(
    districts: Mapping[str, District],
    schemes: Mapping[str, SchemeInfo],
    config: SyntheticConfig = SyntheticConfig(),
) -> SyntheticDataset:
    """Build the synthetic dataset in memory. Deterministic for a given (config, districts, schemes)."""
    unknown = [d for d in config.district_ids if d not in districts]
    if unknown:
        raise ValueError(f"Unknown district ids (not in mp_districts.geojson): {unknown}")
    rng = random.Random(config.seed)  # noqa: S311 - reproducible demo data, not security-sensitive
    scheme_ids = sorted(schemes)
    label = config.dataset_label
    data = SyntheticDataset()

    for district_id in config.district_ids:
        # Area effects shift the enrolment probability so that some districts/blocks/villages lag behind.
        district_effect = rng.uniform(-0.15, 0.10)
        for b in range(1, rng.randint(*config.blocks_per_district) + 1):
            block_id = f"{district_id}_b{b:02d}"
            block_effect = rng.uniform(-0.25, 0.10)
            data.blocks.append(
                {
                    "block_id": block_id,
                    "block_name": f"Block {b:02d} (synthetic)",
                    "district_id": district_id,
                    "is_synthetic": "true",
                    "dataset_label": label,
                }
            )
            for v in range(1, rng.randint(*config.villages_per_block) + 1):
                village_id = f"{block_id}_v{v:03d}"
                village_effect = rng.uniform(-0.10, 0.10)
                rural = rng.random() < 0.85
                enrol_shift = district_effect + block_effect + village_effect
                households = rng.randint(*config.households_per_village)
                population = 0
                for h in range(1, households + 1):
                    household_id = f"{village_id}_h{h:03d}"
                    members = _draw_members(rng, rng.randint(*config.members_per_household))
                    population += len(members)
                    for m, (age, gender) in enumerate(members, start=1):
                        citizen_id = f"{household_id}_m{m}"
                        for scheme_id in scheme_ids:
                            draw = SCHEME_DRAWS.get(scheme_id, DEFAULT_DRAW)
                            if not _in_target(
                                draw.target, is_head=m == 1, age=age, gender=gender, rural=rural
                            ):
                                continue
                            data.scheme_status.append(
                                _draw_status(
                                    rng,
                                    draw,
                                    schemes[scheme_id].required_documents,
                                    config.missing_document_rate,
                                    enrol_shift,
                                    record={
                                        "record_id": f"{citizen_id}:{scheme_id}",
                                        "citizen_id": citizen_id,
                                        "household_id": household_id,
                                        "village_id": village_id,
                                        "scheme_id": scheme_id,
                                    },
                                    label=label,
                                )
                            )
                data.villages.append(
                    {
                        "village_id": village_id,
                        "village_name": f"Village {v:03d} (synthetic)",
                        "block_id": block_id,
                        "district_id": district_id,
                        "households": str(households),
                        "population": str(population),
                        "is_synthetic": "true",
                        "dataset_label": label,
                    }
                )

    data.manifest = {
        "dataset_label": label,
        "is_synthetic": True,
        "description": NOT_GOVERNMENT_DATA,
        "generator": "ai_modules.analytics.synthetic",
        "generator_version": GENERATOR_VERSION,
        "config": {k: list(v) if isinstance(v, tuple) else v for k, v in asdict(config).items()},
        "scheme_ids": scheme_ids,
        "counts": {
            "districts": len(config.district_ids),
            "blocks": len(data.blocks),
            "villages": len(data.villages),
            "scheme_status_records": len(data.scheme_status),
        },
    }
    return data


def _draw_members(rng: random.Random, count: int) -> list[tuple[int, str]]:
    """Household head (25-70) first, then other members (0-80)."""
    members = [(rng.randint(25, 70), rng.choice(("male", "female")))]
    members += [(rng.randint(0, 80), rng.choice(("male", "female"))) for _ in range(count - 1)]
    return members


def _in_target(target: str, *, is_head: bool, age: int, gender: str, rural: bool) -> bool:
    if target == "household":
        return is_head
    if target == "student":
        return 16 <= age <= 25
    if target == "rural_female_student":
        return rural and gender == "female" and 16 <= age <= 25
    if target == "adult":
        return age >= 18
    raise ValueError(f"Unknown synthetic target group '{target}'")


def _draw_status(
    rng: random.Random,
    draw: SchemeDraw,
    required_documents: Sequence[str],
    missing_document_rate: float,
    enrol_shift: float,
    *,
    record: dict[str, str],
    label: str,
) -> dict[str, str]:
    roll = rng.random()
    missing: list[str] = []
    enrolled = False
    if roll < draw.eligible_rate:
        status = "eligible"
        enrolled = rng.random() < _clip(draw.enrol_rate + enrol_shift)
        if not enrolled:
            missing = [doc for doc in required_documents if rng.random() < missing_document_rate]
    elif roll < draw.eligible_rate + draw.potential_rate:
        status = "potentially_eligible"
        if required_documents:
            missing = sorted(
                rng.sample(list(required_documents), k=min(len(required_documents), rng.randint(1, 2)))
            )
    else:
        status = "not_eligible"
    return {
        **record,
        "eligibility_status": status,
        "enrolled": _bool(enrolled),
        "missing_documents": DOCUMENT_SEPARATOR.join(missing),
        "is_synthetic": "true",
        "dataset_label": label,
    }


def write_dataset(data: SyntheticDataset, output_dir: Path = DEFAULT_INPUT_DIR) -> Path:
    """Write the dataset as UTF-8 CSV (LF line endings) + manifest.json; returns the directory."""
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    for name, columns, rows in (
        ("blocks.csv", BLOCK_COLUMNS, data.blocks),
        ("villages.csv", VILLAGE_COLUMNS, data.villages),
        ("scheme_status.csv", STATUS_COLUMNS, data.scheme_status),
    ):
        with (output_dir / name).open("w", encoding="utf-8", newline="") as fh:
            writer = csv.DictWriter(fh, fieldnames=columns, lineterminator="\n")
            writer.writeheader()
            writer.writerows(rows)
    with (output_dir / "manifest.json").open("w", encoding="utf-8", newline="\n") as fh:
        json.dump(data.manifest, fh, indent=2, sort_keys=True)
        fh.write("\n")
    return output_dir


def read_manifest(input_dir: Path) -> dict:
    with (Path(input_dir) / "manifest.json").open(encoding="utf-8") as fh:
        return json.load(fh)
