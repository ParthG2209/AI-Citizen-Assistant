"""Render clearly watermarked SYNTHETIC certificates with known ground truth.

Used by ``scripts/generate_synthetic_documents.py`` and the OCR tests. Nothing produced here
is a real government document: every page carries "SYNTHETIC SAMPLE" banners and a diagonal
watermark, people are random fictional combinations, and identifier numbers are deliberately
invalid (the Aadhaar-like number starts with 0, which real Aadhaar numbers never do).

Layouts are simplified approximations for testing the pipeline, not copies of official forms.
Pages are laid out with PyMuPDF's HTML engine (HarfBuzz shaping, so Devanagari conjuncts and
matras render correctly), giving a "digital" PDF with a text layer; the PNG is a raster of it.

Bilingual (Hindi + English) variants need a Devanagari font: ``ACA_DEVANAGARI_FONT`` (path to a
.ttf/.ttc), else Nirmala UI on Windows, else Noto Sans Devanagari on Linux (``apt install
fonts-noto-core``). Without one, ``devanagari_font()`` returns ``None`` and only English
variants can be generated.
"""

from __future__ import annotations

import html
import json
import os
import random
from dataclasses import asdict, dataclass, field
from datetime import date, timedelta
from pathlib import Path
from typing import Any

from ai_modules.ocr.normalizer import MP_DISTRICTS, age_on

DOC_TYPES = ("income_certificate", "caste_certificate", "samagra_domicile", "class12_marksheet")
VARIANTS = ("en", "bilingual")
PAGE_DPI = 150
_FONT_CANDIDATES = (
    "C:/Windows/Fonts/Nirmala.ttc",
    "C:/Windows/Fonts/Nirmala.ttf",
    "C:/Windows/Fonts/mangal.ttf",
    "/usr/share/fonts/truetype/noto/NotoSansDevanagari-Regular.ttf",
    "/usr/share/fonts/opentype/noto/NotoSansDevanagari-Regular.ttf",
    "/usr/share/fonts/noto/NotoSansDevanagari-Regular.ttf",
    "/Library/Fonts/Kohinoor.ttc",
)

_FIRST_NAMES = ("Priya", "Ramesh", "Sunita", "Arjun", "Kavita", "Mohan", "Pooja", "Rahul", "Anita", "Vikas")
_FEMALE = {"Priya", "Sunita", "Kavita", "Pooja", "Anita"}
_SURNAMES = ("Verma", "Patel", "Yadav", "Sharma", "Kushwaha", "Meena", "Thakur", "Rajput", "Lodhi", "Sahu")
_CATEGORY_TEXT = {
    "obc": ("Other Backward Class (OBC)", "अन्य पिछड़ा वर्ग"),
    "sc": ("Scheduled Caste (SC)", "अनुसूचित जाति"),
    "st": ("Scheduled Tribe (ST)", "अनुसूचित जनजाति"),
}
_GENDER_TEXT = {"female": ("Female", "महिला"), "male": ("Male", "पुरुष")}
_RESIDENCE_TEXT = {"rural": ("Rural", "ग्रामीण"), "urban": ("Urban", "शहरी")}


@dataclass(slots=True)
class SyntheticDocument:
    doc_id: str
    document_type: str
    variant: str
    expected_fields: dict[str, Any]
    as_of: str  # date used to compute age from the date of birth
    synthetic_identifiers: dict[str, str] = field(default_factory=dict)
    is_synthetic: bool = True
    note: str = "SYNTHETIC test document generated by ai_modules.ocr.synthetic; not a real record."


def devanagari_font() -> Path | None:
    configured = os.getenv("ACA_DEVANAGARI_FONT")
    for candidate in (configured, *_FONT_CANDIDATES):
        if candidate and Path(candidate).is_file():
            return Path(candidate)
    return None


def _indian_grouping(amount: int) -> str:
    """1,20,000 style grouping."""
    digits = str(amount)
    if len(digits) <= 3:
        return digits
    head, tail = digits[:-3], digits[-3:]
    groups = []
    while len(head) > 2:
        groups.insert(0, head[-2:])
        head = head[:-2]
    if head:
        groups.insert(0, head)
    return ",".join(groups) + "," + tail


def _fake_aadhaar(rng: random.Random) -> str:
    # Real Aadhaar numbers never start with 0 or 1; this one is deliberately invalid.
    digits = "0" + "".join(str(rng.randint(0, 9)) for _ in range(11))
    return f"{digits[:4]} {digits[4:8]} {digits[8:]}"


def make_profile(rng: random.Random, as_of: date) -> dict[str, Any]:
    first = rng.choice(_FIRST_NAMES)
    district = rng.choice(MP_DISTRICTS)
    birth = as_of - timedelta(days=rng.randint(17 * 365, 60 * 365))
    obtained = rng.randint(280, 480)
    return {
        "full_name": f"{first} {rng.choice(_SURNAMES)}",
        "father_name": f"{rng.choice(sorted(set(_FIRST_NAMES) - _FEMALE))} {rng.choice(_SURNAMES)}",
        "gender": "female" if first in _FEMALE else "male",
        "district": district.name,
        "district_hi": district.aliases[0],
        "annual_family_income": rng.randrange(36_000, 780_000, 1_000),
        "social_category": rng.choice(sorted(_CATEGORY_TEXT)),
        "birth_date": birth,
        "age": age_on(birth, as_of),
        "residence_type": rng.choice(sorted(_RESIDENCE_TEXT)),
        "marks_obtained": obtained,
        "marks_maximum": 500,
        "class12_board": rng.choice(("mpbse", "cbse")),
        "class12_passing_year": rng.randint(as_of.year - 4, as_of.year - 1),
        "samagra_member_id": "".join(str(rng.randint(0, 9)) for _ in range(9)),
        "aadhaar_like": _fake_aadhaar(rng),
    }


def _rows(doc_type: str, p: dict[str, Any], bilingual: bool) -> tuple[str, str, list[tuple[str, str]], dict]:
    """Return (issuer, title, label/value rows, expected fields) for one document."""

    def lbl(hi: str, en: str) -> str:
        return f"{hi} / {en}" if bilingual else en

    def pick(pair: tuple[str, str]) -> str:
        return pair[1] if bilingual else pair[0]

    district = p["district_hi"] if bilingual else p["district"]
    name_row = (lbl("आवेदक का नाम", "Name of Applicant"), p["full_name"])
    father_row = (lbl("पिता का नाम", "Father's Name"), p["father_name"])
    gov = "मध्यप्रदेश शासन / Government of Madhya Pradesh" if bilingual else "Government of Madhya Pradesh"

    if doc_type == "income_certificate":
        amount = _indian_grouping(p["annual_family_income"])
        rows = [
            name_row,
            father_row,
            (lbl("जिला", "District"), district),
            (lbl("वार्षिक आय", "Annual Family Income"), f"{'रु.' if bilingual else 'Rs.'} {amount}/-"),
            (lbl("जारी दिनांक", "Date of Issue"), "01/04/2025"),
        ]
        expected = {k: p[k] for k in ("full_name", "annual_family_income", "district")}
        return f"{gov}<br>Office of the Tehsildar", lbl("आय प्रमाण-पत्र", "INCOME CERTIFICATE"), rows, expected

    if doc_type == "caste_certificate":
        rows = [
            name_row,
            father_row,
            (lbl("वर्ग", "Category"), pick(_CATEGORY_TEXT[p["social_category"]])),
            (lbl("जिला", "District"), district),
        ]
        expected = {k: p[k] for k in ("full_name", "social_category", "district")}
        title = lbl("जाति प्रमाण-पत्र", "CASTE CERTIFICATE")
        return f"{gov}<br>Office of the Sub-Divisional Officer (Revenue)", title, rows, expected

    if doc_type == "samagra_domicile":
        rows = [
            (lbl("समग्र सदस्य आईडी", "Samagra Member ID"), p["samagra_member_id"]),
            (lbl("सदस्य का नाम", "Name of Member"), p["full_name"]),
            (lbl("लिंग", "Gender"), pick(_GENDER_TEXT[p["gender"]])),
            (
                (lbl("जन्म तिथि", "Date of Birth"), p["birth_date"].strftime("%d/%m/%Y"))
                if bilingual
                else ("Age", f"{p['age']} Years")
            ),
            (lbl("निवास क्षेत्र", "Residence"), pick(_RESIDENCE_TEXT[p["residence_type"]])),
            (lbl("जिला", "District"), district),
            (lbl("राज्य", "State"), "मध्य प्रदेश" if bilingual else "Madhya Pradesh"),
            (lbl("आधार क्रमांक", "Aadhaar No."), p["aadhaar_like"]),
        ]
        expected = {k: p[k] for k in ("full_name", "district", "gender", "age", "residence_type")}
        expected |= {"domicile_state": "Madhya Pradesh", "has_samagra_id": True}
        title = lbl(
            "समग्र सदस्य प्रोफ़ाइल एवं मूल निवासी प्रमाण-पत्र", "SAMAGRA MEMBER PROFILE AND DOMICILE CERTIFICATE"
        )
        return f"{gov}<br>Samagra Samajik Suraksha Mission", title, rows, expected

    if doc_type == "class12_marksheet":
        if p["class12_board"] == "mpbse":
            issuer = (
                "माध्यमिक शिक्षा मण्डल, मध्यप्रदेश, भोपाल<br>Board of Secondary Education, Madhya Pradesh, Bhopal"
                if bilingual
                else "Board of Secondary Education, Madhya Pradesh, Bhopal"
            )
            title = lbl("हायर सेकेण्डरी परीक्षा अंक सूची", "HIGHER SECONDARY (CLASS XII) STATEMENT OF MARKS")
        else:
            issuer = "Central Board of Secondary Education"
            title = "SENIOR SCHOOL CERTIFICATE EXAMINATION (CLASS XII) STATEMENT OF MARKS"
        obtained, maximum = p["marks_obtained"], p["marks_maximum"]
        rows = [
            (lbl("परीक्षार्थी का नाम", "Name of Candidate"), p["full_name"]),
            father_row,
            (lbl("परीक्षा वर्ष", "Year of Examination"), str(p["class12_passing_year"])),
            (lbl("कुल प्राप्तांक", "Grand Total"), f"{obtained} / {maximum}"),
        ]
        if not bilingual:  # bilingual variant exercises the computed-percentage path
            rows.append(("Percentage", f"{obtained * 100 / maximum:.2f}%"))
        rows.append((lbl("परिणाम", "Result"), "PASS"))
        expected = {k: p[k] for k in ("full_name", "class12_board", "class12_passing_year")}
        expected["class12_percentage"] = round(obtained * 100 / maximum, 2)
        return issuer, title, rows, expected

    raise ValueError(f"Unknown document type {doc_type}")


_CSS = """
* {{ font-family: {family}; color: #111; }}
.issuer {{ text-align: center; font-size: 13pt; font-weight: bold; }}
.title {{ text-align: center; font-size: 15pt; font-weight: bold; }}
.cell {{ font-size: 13pt; }}
"""


def render_document(doc_type: str, variant: str, profile: dict[str, Any]) -> tuple[bytes, dict[str, Any]]:
    """Render one synthetic document as a single-page PDF; returns (pdf bytes, expected fields)."""
    import pymupdf

    bilingual = variant == "bilingual"
    font = devanagari_font()
    if bilingual and font is None:
        raise RuntimeError("No Devanagari font found; set ACA_DEVANAGARI_FONT to a .ttf/.ttc file")
    issuer, title, rows, expected = _rows(doc_type, profile, bilingual)

    archive = pymupdf.Archive(str(font.parent)) if font else None
    css = _CSS.format(family="deva" if font else "sans-serif")
    if font is not None:
        css = f"@font-face {{font-family: deva; src: url({font.name});}}\n{css}"

    def box(rect: tuple[float, float, float, float], markup: str) -> None:
        page.insert_htmlbox(pymupdf.Rect(*rect), markup, css=css, archive=archive)

    with pymupdf.open() as pdf:
        page = pdf.new_page(width=595, height=842)  # A4 in points
        _watermark(page)
        box((50, 70, 545, 120), f"<div class='issuer'>{issuer}</div>")
        box((50, 125, 545, 185), f"<div class='title'>{html.escape(title)}</div>")
        y = 205.0
        for label, value in rows:  # label column | value column, one row per field
            box((50, y, 330, y + 30), f"<div class='cell'>{html.escape(label)}:</div>")
            box((345, y, 545, y + 30), f"<div class='cell'>{html.escape(value)}</div>")
            y += 40
        pdf.subset_fonts()  # otherwise every text box embeds the whole (multi-MB) font collection
        return pdf.tobytes(garbage=4, deflate=True), expected


def _watermark(page: Any) -> None:
    import pymupdf

    red = (0.75, 0.05, 0.05)
    banner = "SYNTHETIC SAMPLE - NOT A REAL GOVERNMENT DOCUMENT - FOR TESTING ONLY"
    page.insert_text((50, 40), banner, fontsize=9, color=red)
    page.insert_text((50, 815), banner, fontsize=9, color=red)
    # Diagonal watermark in the lower part of the page, clear of the field rows (which end ~y=530).
    pivot = pymupdf.Point(300, 700)
    page.insert_text(
        (120, 730), "SYNTHETIC", fontsize=90, color=(0.9, 0.9, 0.9), morph=(pivot, pymupdf.Matrix(-15))
    )


def pdf_to_png(pdf_bytes: bytes, dpi: int = PAGE_DPI) -> bytes:
    import pymupdf

    with pymupdf.open(stream=pdf_bytes, filetype="pdf") as pdf:
        return pdf[0].get_pixmap(dpi=dpi, alpha=False).tobytes("png")


def image_to_pdf(image_bytes: bytes) -> bytes:
    """Wrap a raster image into an image-only ("scanned") PDF without a text layer."""
    import pymupdf

    with pymupdf.open() as pdf:
        page = pdf.new_page(width=595, height=842)
        page.insert_image(page.rect, stream=image_bytes)
        return pdf.tobytes(deflate=True)


def generate(
    out_dir: Path,
    *,
    seed: int = 2025,
    per_type: int = 1,
    variants: tuple[str, ...] = VARIANTS,
    as_of: date | None = None,
) -> list[SyntheticDocument]:
    """Write ``<id>.png``, ``<id>.pdf`` and ``<id>.json`` (ground truth) per document."""
    as_of = as_of or date.today()
    rng = random.Random(seed)  # noqa: S311 - reproducible fake test data, not security-sensitive
    if "bilingual" in variants and devanagari_font() is None:
        variants = tuple(v for v in variants if v != "bilingual")
    out_dir.mkdir(parents=True, exist_ok=True)
    docs: list[SyntheticDocument] = []
    for doc_type in DOC_TYPES:
        for variant in variants:
            for n in range(per_type):
                profile = make_profile(rng, as_of)
                pdf_bytes, expected = render_document(doc_type, variant, profile)
                doc_id = f"synthetic_{doc_type}_{variant}_{n + 1:02d}"
                (out_dir / f"{doc_id}.pdf").write_bytes(pdf_bytes)
                (out_dir / f"{doc_id}.png").write_bytes(pdf_to_png(pdf_bytes))
                identifiers: dict[str, str] = {}
                if doc_type == "samagra_domicile":  # the only layout that prints these fake numbers
                    identifiers = {
                        "aadhaar_like": profile["aadhaar_like"],
                        "samagra_member_id": profile["samagra_member_id"],
                    }
                doc = SyntheticDocument(doc_id, doc_type, variant, expected, as_of.isoformat(), identifiers)
                (out_dir / f"{doc_id}.json").write_text(
                    json.dumps(asdict(doc), ensure_ascii=False, indent=2), encoding="utf-8"
                )
                docs.append(doc)
    return docs
